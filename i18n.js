const PH = { 'Search… try 2160p  >10GB  offline': 'खोजें… जैसे 2160p  >10GB  offline' };

let i18nLang = 'en';
const i18nOrig = new WeakMap();      // text node -> original English
const ATTRS = ['placeholder', 'title', 'aria-label'];

function trHi(text) {
  const t = text.trim();
  if (!t) return null;
  const hit = HI[t] || PH[t];
  return hit ? text.replace(t, hit) : null;
}

function translateTree(root) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = []; for (let n = walker.nextNode(); n; n = walker.nextNode()) nodes.push(n);
  for (const n of nodes) {
    const p = n.parentNode && n.parentNode.nodeName;
    if (p === 'SCRIPT' || p === 'STYLE' || p === 'TEXTAREA') continue;
    if (i18nLang === 'hi') {
      const orig = i18nOrig.has(n) ? i18nOrig.get(n) : n.nodeValue;
      const out = trHi(orig);
      if (out != null) { if (!i18nOrig.has(n)) i18nOrig.set(n, orig); if (n.nodeValue !== out) n.nodeValue = out; }
      else if (i18nOrig.has(n) && n.nodeValue === trHi(i18nOrig.get(n))) { /* unchanged translation */ }
    } else if (i18nOrig.has(n)) { n.nodeValue = i18nOrig.get(n); i18nOrig.delete(n); }
  }
  const els = root.querySelectorAll ? root.querySelectorAll('[placeholder],[title],[aria-label]') : [];
  for (const el of els) for (const a of ATTRS) {
    if (!el.hasAttribute(a)) continue;
    const key = `data-en-${a}`;
    if (i18nLang === 'hi') {
      const orig = el.hasAttribute(key) ? el.getAttribute(key) : el.getAttribute(a);
      const out = trHi(orig);
      if (out != null) { if (!el.hasAttribute(key)) el.setAttribute(key, orig); if (el.getAttribute(a) !== out) el.setAttribute(a, out); }
    } else if (el.hasAttribute(key)) { el.setAttribute(a, el.getAttribute(key)); el.removeAttribute(key); }
  }
}

let i18nObs = null, i18nBusy = false;
function setLanguage(lang) {
  i18nLang = lang === 'hi' ? 'hi' : 'en';
  document.documentElement.lang = i18nLang;
  const run = () => { if (i18nBusy) return; i18nBusy = true; try { translateTree(document.body); } finally { i18nBusy = false; } };
  run();
  if (!i18nObs) {
    let t = null;
    i18nObs = new MutationObserver(() => { if (i18nBusy || i18nLang !== 'hi') return; clearTimeout(t); t = setTimeout(run, 30); });
    i18nObs.observe(document.body, { childList: true, subtree: true, characterData: true });
  }
}
